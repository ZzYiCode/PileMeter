from __future__ import annotations

import math
from collections.abc import Iterable, Sequence
from pathlib import Path

Point = tuple[float, float, float]
Color = tuple[int, int, int]


def _normalize_points(points: Iterable[Sequence[float]]) -> list[Point]:
    normalized: list[Point] = []
    for index, point in enumerate(points):
        if len(point) != 3:
            raise ValueError(f"Point {index} must contain exactly three coordinates")
        values = tuple(float(value) for value in point)
        if not all(math.isfinite(value) for value in values):
            raise ValueError(f"Point {index} contains a non-finite coordinate")
        normalized.append(values)
    if not normalized:
        raise ValueError("Point cloud must contain at least one point")
    return normalized


def _normalize_colors(
    colors: Iterable[Sequence[int]] | None,
    point_count: int,
) -> list[Color]:
    if colors is None:
        return [(210, 214, 218)] * point_count

    normalized: list[Color] = []
    for index, color in enumerate(colors):
        if len(color) != 3:
            raise ValueError(f"Color {index} must contain exactly three channels")
        values = tuple(max(0, min(255, int(channel))) for channel in color)
        normalized.append(values)
    if len(normalized) != point_count:
        raise ValueError("Point and color counts must match")
    return normalized


def write_ascii_ply(
    path: Path | str,
    points: Iterable[Sequence[float]],
    colors: Iterable[Sequence[int]] | None = None,
) -> Path:
    """Write a point cloud as a portable ASCII PLY file."""

    output_path = Path(path)
    normalized_points = _normalize_points(points)
    normalized_colors = _normalize_colors(colors, len(normalized_points))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_suffix(f"{output_path.suffix}.tmp")

    header = [
        "ply",
        "format ascii 1.0",
        "comment generated by PileMeter",
        f"element vertex {len(normalized_points)}",
        "property float x",
        "property float y",
        "property float z",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        "end_header",
    ]

    with temporary_path.open("w", encoding="ascii", newline="\n") as stream:
        stream.write("\n".join(header))
        stream.write("\n")
        for point, color in zip(normalized_points, normalized_colors, strict=True):
            stream.write(
                f"{point[0]:.6f} {point[1]:.6f} {point[2]:.6f} {color[0]} {color[1]} {color[2]}\n"
            )

    temporary_path.replace(output_path)
    return output_path
