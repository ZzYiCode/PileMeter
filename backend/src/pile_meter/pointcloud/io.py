from __future__ import annotations

import math
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

Point = tuple[float, float, float]
Color = tuple[int, int, int]


def _normalize_points(points: Iterable[Sequence[float]]) -> list[Point]:
    normalized: list[Point] = []
    for index, point in enumerate(points):
        if len(point) != 3:
            raise ValueError(f"Point {index} must contain exactly three coordinates")
        values = tuple(float(value) for value in point)
        if not all(math.isfinite(value) for value in values):
            raise ValueError(f"Point {index} contains a non-finite coordinate")
        normalized.append(values)
    if not normalized:
        raise ValueError("Point cloud must contain at least one point")
    return normalized


def _normalize_colors(
    colors: Iterable[Sequence[int]] | None,
    point_count: int,
) -> list[Color]:
    if colors is None:
        return [(210, 214, 218)] * point_count

    normalized: list[Color] = []
    for index, color in enumerate(colors):
        if len(color) != 3:
            raise ValueError(f"Color {index} must contain exactly three channels")
        values = tuple(max(0, min(255, int(channel))) for channel in color)
        normalized.append(values)
    if len(normalized) != point_count:
        raise ValueError("Point and color counts must match")
    return normalized


def write_ascii_ply(
    path: Path | str,
    points: Iterable[Sequence[float]],
    colors: Iterable[Sequence[int]] | None = None,
) -> Path:
    """Write a point cloud as a portable ASCII PLY file."""

    output_path = Path(path)
    normalized_points = _normalize_points(points)
    normalized_colors = _normalize_colors(colors, len(normalized_points))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_suffix(f"{output_path.suffix}.tmp")

    header = [
        "ply",
        "format ascii 1.0",
        "comment generated by PileMeter",
        f"element vertex {len(normalized_points)}",
        "property float x",
        "property float y",
        "property float z",
        "property uchar red",
        "property uchar green",
        "property uchar blue",
        "end_header",
    ]

    with temporary_path.open("w", encoding="ascii", newline="\n") as stream:
        stream.write("\n".join(header))
        stream.write("\n")
        for point, color in zip(normalized_points, normalized_colors, strict=True):
            stream.write(
                f"{point[0]:.6f} {point[1]:.6f} {point[2]:.6f} {color[0]} {color[1]} {color[2]}\n"
            )

    temporary_path.replace(output_path)
    return output_path


def write_binary_ply(
    path: Path | str,
    points: Any,
    colors: Any,
) -> Path:
    """Write an efficient binary little-endian PLY point cloud.

    NumPy is imported lazily so the lightweight API and ASCII export remain
    usable without installing the reconstruction dependencies.
    """

    import numpy as np

    output_path = Path(path)
    point_array = np.asarray(points, dtype=np.float32)
    color_array = np.asarray(colors, dtype=np.uint8)

    if point_array.ndim != 2 or point_array.shape[1] != 3:
        raise ValueError("Points must have shape (N, 3)")
    if color_array.ndim != 2 or color_array.shape[1] != 3:
        raise ValueError("Colors must have shape (N, 3)")
    if len(point_array) != len(color_array):
        raise ValueError("Point and color counts must match")
    if not np.isfinite(point_array).all():
        raise ValueError("Point cloud contains non-finite coordinates")

    vertex_dtype = np.dtype(
        [
            ("x", "<f4"),
            ("y", "<f4"),
            ("z", "<f4"),
            ("red", "u1"),
            ("green", "u1"),
            ("blue", "u1"),
        ]
    )
    vertices = np.empty(len(point_array), dtype=vertex_dtype)
    vertices["x"] = point_array[:, 0]
    vertices["y"] = point_array[:, 1]
    vertices["z"] = point_array[:, 2]
    vertices["red"] = color_array[:, 0]
    vertices["green"] = color_array[:, 1]
    vertices["blue"] = color_array[:, 2]

    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_suffix(f"{output_path.suffix}.tmp")
    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment generated by PileMeter\n"
        f"element vertex {len(point_array)}\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n"
        "end_header\n"
    )
    with temporary_path.open("wb") as stream:
        stream.write(header.encode("ascii"))
        vertices.tofile(stream)
    temporary_path.replace(output_path)
    return output_path
